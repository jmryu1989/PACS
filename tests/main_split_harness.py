# coding: utf-8
"""S9-U0a-PRE browser harness for temporary split pages (test side only; the product tree is never written).

Small pieces that the first move part can reuse:

* ``build(count, out_dir)`` / ``ScratchPages`` - temporary 18/30/45-part (or unsplit, count 0) copies of the page
  under test, generated by main_split_harness.cjs from tests/main_move_spec.json and checked with the move
  contract (same statements, bytes and outer markup). Each copy comes with a manifest that maps every top-level
  statement to its module and its line range in the served layout.
* ``Delivery`` - a Playwright route that serves one layout's scripts and decides when each answer arrives:
  every split boundary may be delayed (0 ms / 150 ms after the previous script), and one script may be held
  until ``release()``. Answers are only delivered from ``pump()``/route callbacks, so cases drive time through
  ``Delivery.wait()``.
* ``TRACE_SCRIPT`` - an init script that records, before any page script runs, every listener registration
  (addEventListener/removeEventListener and on* handler properties) with its target, type, options, listener
  source hash and the page frames that registered it, every dispatch to a recorded listener with its outcome,
  every script that finished executing, and uncaught errors. Listeners are called unchanged and nothing is
  caught: an exception leaves the listener as before (same error, same reported location) and the window's error
  report that follows is attached to that dispatch.
* ``derive_spec(page, out)`` - the move spec's runs for a page that changed since the move baseline.
* ``fixture_blocks(page, ranges)`` - the TypeScript-AST fixture projection for tests that compile part of the page's
  script: runs of the f1d5406 statements, named by their first and end declarations, taken from the page wherever
  they now sit (``REPORT_FIXTURE`` is the pair the report harness tests use).

What a case asserts is browser-observed behaviour (registrations, dispatch outcomes, what the screen shows), never
implementation strings (AGENTS 1-B). Statement names appear only in the manifest, to tell a reader where a
registration came from.
"""
