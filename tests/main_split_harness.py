def build(count, out_dir, page=None, spec=None):
    """Write the `count`-part layout of `page` (default: the product main.html) into `out_dir`; return its manifest."""
    args = ["node", str(_HELPER), "split", str(count), str(out_dir)]
    if page or spec:
        args.append(str(page or PRODUCT_DIR / "main.html"))
    if spec:
        args.append(str(spec))
    return json.loads(subprocess.check_output(args, text=True, encoding="utf-8", cwd=ROOT))


