def canonical(case_id):
    case = u5.CASE_BY_ID[case_id]
    status, body = LITERAL[case_id]
    rows = copy.deepcopy(ROWS.get(case.test, {"report": None, "drafts": [], "versions": []}))
    before = {"audit_max": 900, "audit_total": 0 if case.probe else 4, "audit": [],
              "state": None if case.probe else state_row(**STATE_CHANGES.get(case_id, {})), **rows}
    after = copy.deepcopy(before)
    if case_id in AUDIT:
        after["audit"], after["audit_total"] = [audit_row(case_id)], before["audit_total"] + 1
    return {"id": case_id, "status": status, "body": copy.deepcopy(body),
            "text": json.dumps(body, ensure_ascii=False), "cache_control": "no-store",
            "before": before, "after": after}


