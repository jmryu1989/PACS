    def test_03_wav_fixtures_are_the_pinned_bytes(self):
        wave, other, big = u5.wav(), u5.wav(44100), u5.oversized()
        self.assertEqual((len(wave), hashlib.sha256(wave).hexdigest()),
                         (46, "156075e2635b9b2c186258f4db987ed9fbdfb727f49e5eac4b9a126aefbdf727"))
        self.assertEqual((len(other), hashlib.sha256(other).hexdigest()),
                         (46, "48f304b4730189540fb9a2b9c8d05d6aba5e55b1375efbd9e2ef28ed544a9743"))
        self.assertEqual((u5.WAV_SHA256, u5.WAV_44100_SHA256),
                         (hashlib.sha256(wave).hexdigest(), hashlib.sha256(other).hexdigest()))
        changed = [i for i in range(46) if wave[i] != other[i]]
        self.assertTrue(changed and set(changed) <= set(range(24, 32)), changed)   # only the two rate fields
        self.assertEqual((len(big), set(big)), (1048577, {0}))
