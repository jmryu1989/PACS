    def test_10_pairing_and_run_completeness(self):
        def lines_of(test, records):
            return {line["id"]: line["problems"] for line in u5.evaluate(test, records, CONTEXT)}

        for test, rows in TABLE.items():
            controls = [row[0] for row in rows if row[1] == "control"]
            for control in controls:
                dependents = [row[0] for row in rows if row[3] == control]
                records = [canonical(row[0]) for row in rows if row[0] != control]
                got = lines_of(test, records)
                self.kill("%s/%s-missing" % (test, control), got[control], ["missing-case"])
                for case_id in dependents:
                    self.kill("%s/%s-unpaired-without-%s" % (test, case_id, control), got[case_id], ["unpaired"])
                records = [canonical(row[0]) for row in rows]
                records[[row[0] for row in rows].index(control)]["status"] = 500
                got = lines_of(test, records)
                self.kill("%s/%s-failed" % (test, control), got[control], ["status"])
                for case_id in dependents:
                    self.kill("%s/%s-unpaired-by-failed-%s" % (test, case_id, control), got[case_id], ["unpaired"])
                got = u5.evaluate(test, [canonical(row[0]) for row in rows] + [canonical(control)], CONTEXT)
                for line in got:
                    if line["id"] == control:
                        self.kill("%s/%s-duplicated" % (test, control), line["problems"], ["duplicate-case"])
                    elif line["id"] in dependents:
                        self.kill("%s/%s-unpaired-by-duplicated-%s" % (test, line["id"], control),
                                  line["problems"], ["unpaired"])
            got = u5.evaluate(test, [canonical(row[0]) for row in rows] + [canonical(rows[0][0])], CONTEXT)
            self.kill("%s/%s-duplicated" % (test, rows[0][0]), [line["problems"] for line in got
                                                               if line["id"] == rows[0][0]][0], ["duplicate-case"])
