def logging_copy(original):
    if original.count(ANCHOR) != 1 or ('\n' + ANCHOR) not in original:
        raise GuardFailure('the proxy template anchor must start exactly one line')
    copy = original.replace(ANCHOR, LOGGING_BLOCK + ANCHOR, 1)
    if copy.count(LOGGING_BLOCK) != 1 or copy.replace(LOGGING_BLOCK, '', 1) != original:
        raise GuardFailure('the generated proxy copy is not the baseline template plus the registered logging block')
    return copy


def generated(original, diag):
    config = diag / 'proxy-config'
    return {
        'proxy-config/default.conf.template': (logging_copy(original).encode('utf-8'), 0o644),
        'proxy-config/99-kin-diag-effective-config.sh': (DUMP_SCRIPT.encode('utf-8'), 0o755),
        OVERRIDE: (OVERRIDE_TEXT.format(template=json.dumps(str(config / 'default.conf.template')),
                                        script=json.dumps(str(config / '99-kin-diag-effective-config.sh')),
                                        logs=json.dumps(str(diag / 'proxy-logs'))).encode('utf-8'), 0o644),
    }


def docker_ids(*args):
    done = subprocess.run(['docker', *args], capture_output=True, timeout=60)
    if done.returncode:
        raise GuardFailure('docker %s exited %d' % (' '.join(args), done.returncode))
    return sorted(done.stdout.decode('utf-8', 'replace').split())


def docker_state(networks=True):
    state = {'containers': docker_ids('ps', '-aq'), 'volumes': docker_ids('volume', 'ls', '-q')}
    if networks:
        state['networks'] = docker_ids('network', 'ls', '--filter', 'type=custom', '-q')
    return state


# -------------------------------------------------------------------------------------------------------- sanitization
def _query(match):
    pairs = []
    for part in match.group(2).split('&'):
        key, sep, value = part.partition('=')
        pairs.append(key + sep + ('[REDACTED]' if value and value != '[REDACTED]' else value))
    return match.group(1) + '?' + '&'.join(pairs)


def sanitize_text(text, query=True):
    counts = {}
    for label, pattern, replacement in (('jwt', JWT, '[REDACTED JWT]'), ('bearer_or_basic', AUTH, r'\1 [REDACTED]'),
                                        ('cookie_or_authorization_header', HEADER, r'\1 [REDACTED]'), ('secret_field', FIELD, r'\1"[REDACTED]"')):
        text, count = pattern.subn(replacement, text)
        counts[label] = count
    if query:
        changed = 0

        def replace(match):
            nonlocal changed
            value = _query(match)
            changed += value != match.group(0)
            return value
        text = QUERY.sub(replace, text)
        counts['query_values'] = changed
    return text, counts


def sanitize_stream(source, target):
    """Line-by-line copy for large text files (NetLog); raw bytes are hashed but never uploaded."""
    raw_hash, clean_hash, counts, size = hashlib.sha256(), hashlib.sha256(), {}, 0
    target.parent.mkdir(parents=True, exist_ok=True)
    with open(source, 'rb') as reader, open(target, 'wb') as writer:
        for raw in reader:
            raw_hash.update(raw)
            text, found = sanitize_text(raw.decode('utf-8', 'replace'))
            data = text.encode('utf-8')
            clean_hash.update(data)
            writer.write(data)
            size += len(data)
            for key, value in found.items():
                counts[key] = counts.get(key, 0) + value
    return {'raw_sha256': raw_hash.hexdigest(), 'sha256': clean_hash.hexdigest(), 'bytes': size, 'redactions': counts}


def read_privileged(path):
    try:
        return path.read_bytes()
    except PermissionError:
        return subprocess.run(['sudo', '-n', 'cat', str(path)], capture_output=True, check=True, timeout=60).stdout


def write_manifest(upload):
    rows = {}
    for path in sorted(p for p in upload.rglob('*') if p.is_file() and p.name != 'manifest.json'):
        digest, size = hashlib.sha256(), 0
        with open(path, 'rb') as stream:
            for chunk in iter(lambda: stream.read(1 << 20), b''):
                digest.update(chunk)
                size += len(chunk)
        rows[path.relative_to(upload).as_posix()] = {'sha256': digest.hexdigest(), 'bytes': size}
    (upload / 'manifest.json').write_text(json.dumps({'written_utc': now(), 'files': rows}, indent=1) + '\n', encoding='utf-8')


