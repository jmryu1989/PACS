class GuardFailure(Exception):
    pass


def git(*args, cwd=None, codes=(0,), data=None):
    done = subprocess.run(['git', '-c', 'core.autocrlf=false', *args], cwd=cwd, input=data, capture_output=True)
    if done.returncode not in codes:
        raise GuardFailure('git %s exited %d: %s' % (' '.join(args), done.returncode, done.stderr.decode('utf-8', 'replace').strip()))
    return done


def out(*args, cwd=None):
    return git(*args, cwd=cwd).stdout.decode('utf-8').rstrip('\n')


def blob(rev, path):
    return git('cat-file', 'blob', '%s:%s' % (rev, path)).stdout


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def blob_id(data):
    return hashlib.sha1(b'blob %d\0' % len(data) + data).hexdigest()


def now():
    return datetime.datetime.now(datetime.timezone.utc).isoformat()


def registry():
    return json.loads((HERE / 'preregistration.json').read_text(encoding='utf-8'))


class Record:
    """One JSON evidence file per harness step, written even when a check fails."""

    def __init__(self, kind):
        self.data = {'kind': kind, 'started_utc': now(), 'ended_utc': None, 'result': 'running',
                     'github': {k: os.environ.get(k) for k in GITHUB}, 'checks': []}

    def check(self, name, expected, actual):
        ok = expected == actual
        self.data['checks'].append({'name': name, 'ok': ok, 'expected': expected, 'actual': actual})
        if not ok:
            raise GuardFailure('%s: expected %r, actual %r' % (name, expected, actual))

    def run(self, work, path=None):
        try:
            work()
            self.data['result'] = 'passed'
        except BaseException as error:
            self.data.update(result='failed', error='%s: %s' % (type(error).__name__, error))
            raise
        finally:
            self.data['ended_utc'] = now()
            text = json.dumps(self.data, ensure_ascii=False, indent=1, default=str) + '\n'
            if path is None:
                sys.stdout.buffer.write(text.encode('utf-8'))
                sys.stdout.flush()
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(text.encode('utf-8'))


def result_of(path):
    try:
        return json.loads(path.read_text(encoding='utf-8')).get('result')
    except (OSError, ValueError):
        return None


