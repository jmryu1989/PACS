def job_blocks(text):
    rows = text.split('\n')
    blocks, name = {}, None
    for line in rows[rows.index('jobs:') + 1:]:
        match = re.match(r'^  ([A-Za-z0-9_-]+):$', line)
        if match:
            name = match.group(1)
            blocks[name] = []
        elif name is not None:
            blocks[name].append(line)
    return blocks


def split_job(block):
    header, steps = [], []
    for line in block:
        if line.startswith('      - '):
            steps.append([line])
        elif steps:
            steps[-1].append(line)
        elif line.strip() and not line.strip().startswith('#'):
            header.append(line)
    return header, ['\n'.join(step).rstrip() for step in steps]


def step_name(step):
    match = re.search(r'^      (?:- |  )name: (.*)$', step, re.M)
    return match.group(1) if match else None


def check_workflow(rec, reg, text, original):
    job = reg['native_job']
    rec.check('harness workflow has no automatic trigger', [], re.findall(
        r'^  (push|pull_request|pull_request_target|schedule|workflow_run|workflow_call|repository_dispatch|merge_group|release|issues|issue_comment):', text, re.M))
    rec.check('harness workflow is dispatched by hand', True, '\non:\n  workflow_dispatch:\n' in text)
    rec.check('harness workflow token is read-only', True, '\npermissions:\n  contents: read\n' in text)
    rec.check('no continue-on-error anywhere in the harness workflow', 0, text.count('continue-on-error'))
    rec.check('no secret is referenced', 0, text.count('secrets.'))
    rec.check('no retry action or retry setting', [], re.findall(r'(?i)retry|max[_-]attempts', text))
    ours, theirs = job_blocks(text), job_blocks(original)
    rec.check('one harness job', [job['harness']], sorted(ours))
    o_header, o_steps = split_job(theirs[job['original']])
    h_header, h_steps = split_job(ours[job['harness']])
    rec.check('the original job runner and 40-minute job timeout are kept and nothing is added to the job', o_header, h_header)
    rec.check('harness step order', job['harness_step_names'], [step_name(step) for step in h_steps])
    kept = [step for step in h_steps if not (step_name(step) or '').startswith('Harness - ')]
    rec.check('every original step is kept, in order', len(o_steps), len(kept))
    applied = []
    for index, (theirs_step, ours_step) in enumerate(zip(o_steps, kept)):
        want = theirs_step
        for old, new in job['allowed_step_changes']:
            if old in want:
                want = want.replace(old, new, 1)
                applied.append(old)
        rec.check('original step %d (%s) is kept verbatim except the registered observation changes' % (index, step_name(theirs_step)), want, ours_step)
    rec.check('each registered observation change applies exactly once', sorted(old for old, _ in job['allowed_step_changes']), sorted(applied))
    harness_steps = [step for step in h_steps if (step_name(step) or '').startswith('Harness - ')]
    timeouts = {}
    for step in harness_steps:
        for match in re.finditer(r'^        timeout-minutes: (\d+)$', step, re.M):
            timeouts[step_name(step)] = int(match.group(1))
    rec.check('harness step timeouts are the registered ones', job['harness_step_timeouts'], timeouts)
    rec.check('only the registered harness steps always run', job['always_harness_steps'], [step_name(s) for s in harness_steps if 'if: always()' in s])
    rec.check('harness steps run only the staged harness', [], [step_name(s) for s in harness_steps if '$RUNNER_TEMP/transport-harness' not in s])
    keys = sorted({m.group(1) for step in h_steps for m in re.finditer(r'^          ([A-Z][A-Z0-9_]*): ', step, re.M)})
    rec.check('step environment names are the registered ones', sorted(job['allowed_env_names']), keys)


