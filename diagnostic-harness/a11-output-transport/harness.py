        rec.check('fresh hosted checkout is clean', '', out('status', '--porcelain=v1', '--untracked-files=all', '--ignored'))
        git('checkout', '--quiet', '--detach', reg['baseline']['sha'])
        rec.check('HEAD is the baseline', reg['baseline']['sha'], out('rev-parse', 'HEAD'))
        rec.check('baseline tree is checked out', reg['baseline']['tree'], out('rev-parse', 'HEAD^{tree}'))
        rec.check('baseline workflow file on disk', reg['baseline']['workflow_blob'], blob_id((root / WORKFLOW).read_bytes()))
        rec.check('no tracked, untracked or ignored difference', '', out('status', '--porcelain=v1', '--untracked-files=all', '--ignored'))
